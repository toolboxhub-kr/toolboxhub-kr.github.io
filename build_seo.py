#!/usr/bin/env python3
"""
ToolBox Hub - Programmatic SEO & Portal Automation Pipeline (build_seo.py)

기능:
1. tools/ 폴더 내 모든 HTML 도구 페이지 스캔 및 메타데이터 자동 추출
2. sitemap.xml 자동 생성 (index, 전체 도구 페이지, 정책 페이지 포함)
3. robots.txt 자동 생성
4. assets/js/tools-registry.js 자동 생성 (관련 도구 추천 및 검색 데이터)
5. index.html의 도구 카드 그리드(<!-- AUTO-TOOLS-START/END -->) 및 도구 개수 자동 갱신

사용법:
  python build_seo.py
  python build_seo.py --base-url https://your-domain.com
"""

from __future__ import annotations

import argparse
import html
import json
import re
from datetime import datetime, timezone
from html.parser import HTMLParser
from pathlib import Path
from typing import Any

ROOT_DIR = Path(__file__).resolve().parent
TOOLS_DIR = ROOT_DIR / "tools"
INDEX_FILE = ROOT_DIR / "index.html"
REGISTRY_FILE = ROOT_DIR / "assets" / "js" / "tools-registry.js"
SITEMAP_FILE = ROOT_DIR / "sitemap.xml"
ROBOTS_FILE = ROOT_DIR / "robots.txt"

STATIC_PAGES = [
    ("index.html", "1.0", "daily"),
    ("about.html", "0.5", "monthly"),
    ("privacy.html", "0.3", "yearly"),
    ("contact.html", "0.4", "monthly"),
]


class ToolMetaParser(HTMLParser):
    """HTML <head> 내 <title>과 <meta> 태그에서 도구 메타데이터를 추출합니다."""

    def __init__(self) -> None:
        super().__init__()
        self.in_title = False
        self.title_text = ""
        self.meta: dict[str, str] = {}

    def handle_starttag(self, tag: str, attrs: list[tuple[str, str | None]]) -> None:
        tag_l = tag.lower()
        if tag_l == "title":
            self.in_title = True
        elif tag_l == "meta":
            attr_map = {k.lower(): (v or "") for k, v in attrs}
            name = attr_map.get("name", "").strip().lower()
            content = attr_map.get("content", "").strip()
            if name and content:
                self.meta[name] = content

    def handle_endtag(self, tag: str) -> None:
        if tag.lower() == "title":
            self.in_title = False

    def handle_data(self, data: str) -> None:
        if self.in_title:
            self.title_text += data


def scan_tools() -> list[dict[str, Any]]:
    tools: list[dict[str, Any]] = []
    if not TOOLS_DIR.exists():
        return tools

    for html_file in sorted(TOOLS_DIR.glob("*.html")):
        raw = html_file.read_text(encoding="utf-8")
        parser = ToolMetaParser()
        parser.feed(raw)
        m = parser.meta

        title = m.get("tool:title") or parser.title_text.split("|")[0].strip() or html_file.stem
        category = m.get("tool:category", "유틸리티")
        category_slug = m.get("tool:category_slug", "utility")
        icon = m.get("tool:icon", "🛠️")
        summary = m.get("tool:summary") or m.get("description", "")
        keywords = m.get("tool:keywords", "")
        try:
            order = int(m.get("tool:order", "999"))
        except ValueError:
            order = 999

        mtime = datetime.fromtimestamp(html_file.stat().st_mtime, tz=timezone.utc).strftime("%Y-%m-%d")
        tools.append(
            {
                "slug": html_file.stem,
                "url": f"tools/{html_file.name}",
                "title": title,
                "category": category,
                "category_slug": category_slug,
                "icon": icon,
                "summary": summary,
                "keywords": keywords,
                "order": order,
                "lastmod": mtime,
            }
        )

    tools.sort(key=lambda x: (x["order"], x["title"]))
    return tools


def generate_registry_js(tools: list[dict[str, Any]]) -> None:
    REGISTRY_FILE.parent.mkdir(parents=True, exist_ok=True)
    payload = [
        {
            "slug": t["slug"],
            "url": t["url"],
            "title": t["title"],
            "category": t["category"],
            "category_slug": t["category_slug"],
            "icon": t["icon"],
            "summary": t["summary"],
            "keywords": t["keywords"],
        }
        for t in tools
    ]
    js_content = (
        "// Auto-generated by build_seo.py — do not edit manually.\n"
        f"window.TOOLS_REGISTRY = {json.dumps(payload, ensure_ascii=False, indent=2)};\n"
    )
    REGISTRY_FILE.write_text(js_content, encoding="utf-8")
    print(f"[OK] {REGISTRY_FILE.relative_to(ROOT_DIR)} updated ({len(tools)} tools)")


def build_tool_cards_html(tools: list[dict[str, Any]]) -> str:
    cards = []
    for t in tools:
        search_blob = f"{t['title']} {t['summary']} {t['category']} {t['keywords']}"
        card = f"""        <a class="tool-card" href="{html.escape(t['url'])}" data-cat="{html.escape(t['category_slug'])}" data-search="{html.escape(search_blob)}">
          <div class="tool-card-top">
            <span class="tool-card-icon" aria-hidden="true">{t['icon']}</span>
            <span class="tool-card-cat">{html.escape(t['category'])}</span>
          </div>
          <h3>{html.escape(t['title'])}</h3>
          <p>{html.escape(t['summary'])}</p>
          <span class="tool-card-cta">바로 사용하기 →</span>
        </a>"""
        cards.append(card)
    return "\n".join(cards)


def update_index_html(tools: list[dict[str, Any]]) -> None:
    if not INDEX_FILE.exists():
        print("[WARN] index.html not found; skipping card injection.")
        return

    content = INDEX_FILE.read_text(encoding="utf-8")
    cards_html = build_tool_cards_html(tools)

    content, count_cards = re.subn(
        r"<!-- AUTO-TOOLS-START -->.*?<!-- AUTO-TOOLS-END -->",
        f"<!-- AUTO-TOOLS-START -->\n{cards_html}\n        <!-- AUTO-TOOLS-END -->",
        content,
        flags=re.DOTALL,
    )
    content, count_badge = re.subn(
        r"<!-- AUTO-TOOL-COUNT-START -->.*?<!-- AUTO-TOOL-COUNT-END -->",
        f"<!-- AUTO-TOOL-COUNT-START -->{len(tools)}<!-- AUTO-TOOL-COUNT-END -->",
        content,
        flags=re.DOTALL,
    )

    if count_cards == 0:
        print("[WARN] AUTO-TOOLS markers not found in index.html")
    else:
        INDEX_FILE.write_text(content, encoding="utf-8")
        print(f"[OK] index.html updated ({len(tools)} cards injected, count badge updated: {count_badge > 0})")


def generate_sitemap(tools: list[dict[str, Any]], base_url: str) -> None:
    base = base_url.rstrip("/")
    today = datetime.now(timezone.utc).strftime("%Y-%m-%d")
    entries: list[str] = []

    for filename, priority, freq in STATIC_PAGES:
        path = ROOT_DIR / filename
        if not path.exists():
            continue
        loc = f"{base}/" if filename == "index.html" else f"{base}/{filename}"
        entries.append(
            f"  <url>\n"
            f"    <loc>{html.escape(loc)}</loc>\n"
            f"    <lastmod>{today}</lastmod>\n"
            f"    <changefreq>{freq}</changefreq>\n"
            f"    <priority>{priority}</priority>\n"
            f"  </url>"
        )

    for t in tools:
        loc = f"{base}/{t['url']}"
        entries.append(
            f"  <url>\n"
            f"    <loc>{html.escape(loc)}</loc>\n"
            f"    <lastmod>{t['lastmod']}</lastmod>\n"
            f"    <changefreq>weekly</changefreq>\n"
            f"    <priority>0.9</priority>\n"
            f"  </url>"
        )

    xml = (
        '<?xml version="1.0" encoding="UTF-8"?>\n'
        '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n'
        + "\n".join(entries)
        + "\n</urlset>\n"
    )
    SITEMAP_FILE.write_text(xml, encoding="utf-8")
    print(f"[OK] sitemap.xml generated ({len(entries)} URLs)")


def generate_robots(base_url: str) -> None:
    base = base_url.rstrip("/")
    txt = (
        "User-agent: *\n"
        "Allow: /\n"
        "\n"
        f"Sitemap: {base}/sitemap.xml\n"
    )
    ROBOTS_FILE.write_text(txt, encoding="utf-8")
    print(f"[OK] robots.txt generated (Sitemap: {base}/sitemap.xml)")


def main() -> None:
    parser = argparse.ArgumentParser(description="ToolBox Hub Programmatic SEO Builder")
    parser.add_argument(
        "--base-url",
        default="https://example.com",
        help="배포 도메인 주소 (예: https://mytools.pages.dev)",
    )
    args = parser.parse_args()

    tools = scan_tools()
    generate_registry_js(tools)
    update_index_html(tools)
    generate_sitemap(tools, args.base_url)
    generate_robots(args.base_url)
    print("\n[DONE] Programmatic SEO build complete!")


if __name__ == "__main__":
    main()
