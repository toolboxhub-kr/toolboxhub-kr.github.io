#!/usr/bin/env python3
"""
ToolBox Hub - Bilingual (KO + EN) Programmatic SEO & Portal Automation Pipeline

기능:
1. tools/*.html (한국어) 및 en/tools/*.html (영어) 스캔 및 메타데이터 자동 추출
2. assets/js/tools-registry.js 및 assets/js/en-tools-registry.js 자동 생성
3. index.html 및 en/index.html의 도구 카드 그리드 및 도구 개수 자동 갱신
4. sitemap.xml (KO + EN 전체 URL 포함) 및 robots.txt 자동 생성
"""

from __future__ import annotations

import argparse
import html
import json
import re
from datetime import datetime, timezone
from html.parser import HTMLParser
from pathlib import Path
from typing import Any

ROOT_DIR = Path(__file__).resolve().parent
KO_TOOLS_DIR = ROOT_DIR / "tools"
EN_TOOLS_DIR = ROOT_DIR / "en" / "tools"
KO_INDEX = ROOT_DIR / "index.html"
EN_INDEX = ROOT_DIR / "en" / "index.html"
KO_REGISTRY = ROOT_DIR / "assets" / "js" / "tools-registry.js"
EN_REGISTRY = ROOT_DIR / "assets" / "js" / "en-tools-registry.js"
SITEMAP_FILE = ROOT_DIR / "sitemap.xml"
ROBOTS_FILE = ROOT_DIR / "robots.txt"

STATIC_PAGES = [
    ("index.html", "1.0", "daily"),
    ("en/index.html", "1.0", "daily"),
    ("about.html", "0.5", "monthly"),
    ("privacy.html", "0.3", "yearly"),
    ("contact.html", "0.4", "monthly"),
]


class ToolMetaParser(HTMLParser):
    def __init__(self) -> None:
        super().__init__()
        self.in_title = False
        self.title_text = ""
        self.meta: dict[str, str] = {}

    def handle_starttag(self, tag: str, attrs: list[tuple[str, str | None]]) -> None:
        tag_l = tag.lower()
        if tag_l == "title":
            self.in_title = True
        elif tag_l == "meta":
            attr_map = {k.lower(): (v or "") for k, v in attrs}
            name = attr_map.get("name", "").strip().lower()
            content = attr_map.get("content", "").strip()
            if name and content:
                self.meta[name] = content

    def handle_endtag(self, tag: str) -> None:
        if tag.lower() == "title":
            self.in_title = False

    def handle_data(self, data: str) -> None:
        if self.in_title:
            self.title_text += data


def scan_tools(tools_dir: Path, url_prefix: str) -> list[dict[str, Any]]:
    tools: list[dict[str, Any]] = []
    if not tools_dir.exists():
        return tools

    for html_file in sorted(tools_dir.glob("*.html")):
        raw = html_file.read_text(encoding="utf-8")
        parser = ToolMetaParser()
        parser.feed(raw)
        m = parser.meta

        title = m.get("tool:title") or parser.title_text.split("|")[0].strip() or html_file.stem
        category = m.get("tool:category", "Utilities")
        category_slug = m.get("tool:category_slug", "utility")
        icon = m.get("tool:icon", "🛠️")
        summary = m.get("tool:summary") or m.get("description", "")
        keywords = m.get("tool:keywords", "")
        try:
            order = int(m.get("tool:order", "999"))
        except ValueError:
            order = 999

        mtime = datetime.fromtimestamp(html_file.stat().st_mtime, tz=timezone.utc).strftime("%Y-%m-%d")
        tools.append(
            {
                "slug": html_file.stem,
                "url": f"{url_prefix}/{html_file.name}",
                "rel_href": f"tools/{html_file.name}",
                "title": title,
                "category": category,
                "category_slug": category_slug,
                "icon": icon,
                "summary": summary,
                "keywords": keywords,
                "order": order,
                "lastmod": mtime,
            }
        )

    tools.sort(key=lambda x: (x["order"], x["title"]))
    return tools


def generate_registry_js(tools: list[dict[str, Any]], out_file: Path, var_name: str) -> None:
    out_file.parent.mkdir(parents=True, exist_ok=True)
    payload = [
        {
            "slug": t["slug"],
            "url": t["url"],
            "title": t["title"],
            "category": t["category"],
            "category_slug": t["category_slug"],
            "icon": t["icon"],
            "summary": t["summary"],
            "keywords": t["keywords"],
        }
        for t in tools
    ]
    js_content = (
        "// Auto-generated by build_seo.py — do not edit manually.\n"
        f"window.{var_name} = {json.dumps(payload, ensure_ascii=False, indent=2)};\n"
    )
    out_file.write_text(js_content, encoding="utf-8")
    print(f"[OK] {out_file.relative_to(ROOT_DIR)} updated ({len(tools)} tools)")


def build_tool_cards_html(tools: list[dict[str, Any]], cta_text: str) -> str:
    cards = []
    for t in tools:
        search_blob = f"{t['title']} {t['summary']} {t['category']} {t['keywords']}"
        card = f"""        <a class="tool-card" href="{html.escape(t['rel_href'])}" data-cat="{html.escape(t['category_slug'])}" data-search="{html.escape(search_blob)}">
          <div class="tool-card-top">
            <span class="tool-card-icon" aria-hidden="true">{t['icon']}</span>
            <span class="tool-card-cat">{html.escape(t['category'])}</span>
          </div>
          <h3>{html.escape(t['title'])}</h3>
          <p>{html.escape(t['summary'])}</p>
          <span class="tool-card-cta">{cta_text}</span>
        </a>"""
        cards.append(card)
    return "\n".join(cards)


def update_index_html(index_file: Path, tools: list[dict[str, Any]], cta_text: str) -> None:
    if not index_file.exists():
        return

    content = index_file.read_text(encoding="utf-8")
    cards_html = build_tool_cards_html(tools, cta_text)

    content, count_cards = re.subn(
        r"<!-- AUTO-TOOLS-START -->.*?<!-- AUTO-TOOLS-END -->",
        f"<!-- AUTO-TOOLS-START -->\n{cards_html}\n        <!-- AUTO-TOOLS-END -->",
        content,
        flags=re.DOTALL,
    )
    content, count_badge = re.subn(
        r"<!-- AUTO-TOOL-COUNT-START -->.*?<!-- AUTO-TOOL-COUNT-END -->",
        f"<!-- AUTO-TOOL-COUNT-START -->{len(tools)}<!-- AUTO-TOOL-COUNT-END -->",
        content,
        flags=re.DOTALL,
    )

    if count_cards > 0:
        index_file.write_text(content, encoding="utf-8")
        print(f"[OK] {index_file.relative_to(ROOT_DIR)} updated ({len(tools)} cards, badge: {count_badge > 0})")


def generate_sitemap(all_tools: list[dict[str, Any]], base_url: str) -> None:
    base = base_url.rstrip("/")
    today = datetime.now(timezone.utc).strftime("%Y-%m-%d")
    entries: list[str] = []

    for filename, priority, freq in STATIC_PAGES:
        path = ROOT_DIR / filename
        if not path.exists():
            continue
        if filename == "index.html":
            loc = f"{base}/"
        elif filename == "en/index.html":
            loc = f"{base}/en/"
        else:
            loc = f"{base}/{filename}"
        entries.append(
            f"  <url>\n"
            f"    <loc>{html.escape(loc)}</loc>\n"
            f"    <lastmod>{today}</lastmod>\n"
            f"    <changefreq>{freq}</changefreq>\n"
            f"    <priority>{priority}</priority>\n"
            f"  </url>"
        )

    for t in all_tools:
        loc = f"{base}/{t['url']}"
        entries.append(
            f"  <url>\n"
            f"    <loc>{html.escape(loc)}</loc>\n"
            f"    <lastmod>{t['lastmod']}</lastmod>\n"
            f"    <changefreq>weekly</changefreq>\n"
            f"    <priority>0.9</priority>\n"
            f"  </url>"
        )

    xml = (
        '<?xml version="1.0" encoding="UTF-8"?>\n'
        '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n'
        + "\n".join(entries)
        + "\n</urlset>\n"
    )
    SITEMAP_FILE.write_text(xml, encoding="utf-8")
    print(f"[OK] sitemap.xml generated ({len(entries)} URLs)")


def generate_robots(base_url: str) -> None:
    base = base_url.rstrip("/")
    txt = f"User-agent: *\nAllow: /\n\nSitemap: {base}/sitemap.xml\n"
    ROBOTS_FILE.write_text(txt, encoding="utf-8")
    print(f"[OK] robots.txt generated (Sitemap: {base}/sitemap.xml)")


def main() -> None:
    parser = argparse.ArgumentParser(description="ToolBox Hub Bilingual SEO Builder")
    parser.add_argument("--base-url", default="https://toolboxhub-kr.github.io")
    args = parser.parse_args()

    ko_tools = scan_tools(KO_TOOLS_DIR, "tools")
    en_tools = scan_tools(EN_TOOLS_DIR, "en/tools")

    generate_registry_js(ko_tools, KO_REGISTRY, "TOOLS_REGISTRY")
    update_index_html(KO_INDEX, ko_tools, "바로 사용하기 →")

    if en_tools:
        generate_registry_js(en_tools, EN_REGISTRY, "EN_TOOLS_REGISTRY")
        update_index_html(EN_INDEX, en_tools, "Open Tool →")

    generate_sitemap(ko_tools + en_tools, args.base_url)
    generate_robots(args.base_url)
    print("\n[DONE] Bilingual Programmatic SEO build complete!")


if __name__ == "__main__":
    main()
